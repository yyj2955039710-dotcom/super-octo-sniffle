# ==================== 核心类 ====================
class AuditBusinessScanner:
    """审计商机识别扫描器"""

    def __init__(self, config: dict = None):
        self.config = config or CONFIG
        self.client = OpenAI(api_key=self.config["api_key"])

    def build_prompt(self, title: str, content: str) -> str:
        """构建分类提示词"""
        return f"""{SYSTEM_PROMPT}

{FEW_SHOT_EXAMPLES}

---

【待分类信息】
标题：{title}
正文：{content}

请严格按照上述示例格式输出JSON结果，不要添加任何解释说明。"""

    def classify_single(self, title: str, content: str) -> dict:
        """单条数据分类"""
        prompt = self.build_prompt(title, content)

        response = self.client.chat.completions.create(
            model=self.config["model"],
            messages=[
                {"role": "system", "content": "你是一个严格遵循指令的招投标商机识别助手。必须且只能输出JSON格式结果，不得添加任何解释、说明或额外文字。"},
                {"role": "user", "content": prompt}
            ],
            max_tokens=self.config["max_tokens"],
            temperature=self.config["temperature"]
        )

        result_text = response.choices[0].message.content.strip()

        # 尝试解析JSON
        try:
            # 尝试提取JSON块
            if "```json" in result_text:
                result_text = result_text.split("```json")[1].split("```")[0].strip()
            elif "```" in result_text:
                result_text = result_text.split("```")[1].split("```")[0].strip()

            return json.loads(result_text)
        except json.JSONDecodeError:
            # JSON解析失败，返回错误信息
            return {
                "是否属于商机": "不确定",
                "商机类型": ["解析错误"],
                "推荐跟进": "可观察",
                "跟进优先级": "低",
                "置信度": "低",
                "是否进入人工复核池": "是",
                "关键词": [],
                "判断依据": f"模型输出格式错误，无法解析：{result_text[:200]}",
                "风险提示": "AI输出格式异常，需人工处理"
            }

    def batch_process(self, data_list: list, progress_callback=None) -> list:
        """批量处理数据"""
        results = []
        total = len(data_list)

        for i, item in enumerate(data_list):
            # 提取标题和正文（兼容多种数据格式）
            title = item.get("title") or item.get("标题") or item.get("project_name") or item.get("项目名称", "")
            content = item.get("content") or item.get("正文") or item.get("description") or item.get("采购内容", "")

            try:
                classification = self.classify_single(title, content)

                # 构建结果
                result = {
                    "原始数据": {
                        "标题": title,
                        "内容": content[:500] if content else "",  # 保留前500字符
                    },
                    "分类结果": classification,
                    "扫描时间": datetime.now().isoformat(),
                    "原始ID": item.get("id") or item.get("编号") or item.get("项目编号", f"idx_{i}"),
                }
                results.append(result)

            except Exception as e:
                results.append({
                    "原始数据": {
                        "标题": title,
                        "内容": content[:500] if content else "",
                    },
                    "分类结果": {
                        "是否属于商机": "不确定",
                        "商机类型": ["处理异常"],
                        "推荐跟进": "可观察",
                        "跟进优先级": "低",
                        "置信度": "低",
                        "是否进入人工复核池": "是",
                        "关键词": [],
                        "判断依据": f"处理异常：{str(e)}",
                        "风险提示": "程序处理异常，需人工处理"
                    },
                    "扫描时间": datetime.now().isoformat(),
                    "原始ID": item.get("id") or item.get("编号", f"idx_{i}"),
                    "error": str(e)
                })

            # 进度回调
            if progress_callback:
                progress_callback(i + 1, total)

            # API限流控制
            time.sleep(self.config["rate_limit_delay"])

        return results

    def save_results(self, results: list, output_path: str, format: str = "jsonl"):
        """保存结果到文件"""
        output_path = Path(output_path)
        output_path.parent.mkdir(parents=True, exist_ok=True)

        if format == "jsonl":
            with open(output_path, "w", encoding="utf-8") as f:
                for item in results:
                    f.write(json.dumps(item, ensure_ascii=False) + "\n")
        else:
            with open(output_path, "w", encoding="utf-8") as f:
                json.dump(results, f, ensure_ascii=False, indent=2)

        print(f"结果已保存至: {output_path}")

    def generate_summary(self, results: list) -> dict:
        """生成扫描统计摘要"""
        summary = {
            "总处理数量": len(results),
            "商机识别结果": {
                "是": 0,
                "否": 0,
                "不确定": 0
            },
            "推荐跟进结果": {
                "建议跟进": 0,
                "可观察": 0,
                "不建议跟进": 0
            },
            "优先级分布": {
                "高": 0,
                "中": 0,
                "低": 0
            },
            "进入人工复核池": 0,
            "商机明细": []
        }

        for item in results:
            cls = item.get("分类结果", {})
            is_business = cls.get("是否属于商机", "")
            follow_recommend = cls.get("推荐跟进", "")
            priority = cls.get("跟进优先级", "")
            need_review = cls.get("是否进入人工复核池", "")

            # 统计
            if is_business in summary["商机识别结果"]:
                summary["商机识别结果"][is_business] += 1

            if follow_recommend in summary["推荐跟进结果"]:
                summary["推荐跟进结果"][follow_recommend] += 1

            if priority in summary["优先级分布"]:
                summary["优先级分布"][priority] += 1

            if need_review == "是":
                summary["进入人工复核池"] += 1

            # 提取高价值商机
            if is_business == "是" and follow_recommend == "建议跟进":
                summary["商机明细"].append({
                    "原始ID": item.get("原始ID", ""),
                    "标题": item.get("原始数据", {}).get("标题", ""),
                    "商机类型": cls.get("商机类型", []),
                    "跟进优先级": priority,
                    "置信度": cls.get("置信度", ""),
                    "关键词": cls.get("关键词", [])
                })

        return summary


# ==================== 数据加载器 ====================
class DataLoader:
    """爬虫数据加载器"""

    @staticmethod
    def load_from_json(file_path: str) -> list:
        """从JSON文件加载"""
        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)
            if isinstance(data, list):
                return data
            elif isinstance(data, dict):
                # 兼容单条数据或包含在某个key下
                if "data" in data:
                    return data["data"]
                elif "list" in data:
                    return data["list"]
                elif "items" in data:
                    return data["items"]
                else:
                    return [data]
        return []

    @staticmethod
    def load_from_jsonl(file_path: str) -> list:
        """从JSONL文件加载"""
        results = []
        with open(file_path, "r", encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    results.append(json.loads(line))
        return results

    @staticmethod
    def load_from_csv(file_path: str) -> list:
        """从CSV文件加载"""
        import csv
        results = []
        with open(file_path, "r", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            for row in reader:
                results.append(row)
        return results


